import os
import yaml
import shutil
from ultralytics import YOLO

# ─────────────────────────────────────────────
# CONFIGURATION
# ─────────────────────────────────────────────
BASE_DIR        = '/content/drive/MyDrive/368651_Byzantine_monograms'
SPLITS_DIR      = os.path.join(BASE_DIR, 'splits')
IMAGES_DIR      = os.path.join(BASE_DIR, 'images', 'train')
LABELS_DIR      = os.path.join(BASE_DIR, 'labels', 'train')
DATA_CONFIG     = os.path.join(BASE_DIR, 'data_config.yaml')
OUTPUT_DIR      = os.path.join(BASE_DIR, 'runs')
N_SPLITS        = 5

# Hyperparamètres d'entraînement
MODEL_WEIGHTS   = 'yolov8s.pt'   # poids pré-entraînés YOLOv8 small
EPOCHS          = 100
IMG_SIZE        = 640
BATCH_SIZE      = 16
DEVICE          = 0              # 0 = première GPU CUDA


def load_base_config(config_path):
    """Charge la config YAML de base (noms de classes, nc, couleurs)."""
    with open(config_path, 'r', encoding='utf-8') as f:
        return yaml.safe_load(f)


def build_fold_image_dirs(fold_idx, split):

    fold_img_dir = os.path.join(BASE_DIR, f'_tmp_fold_{fold_idx}', split, 'images')
    fold_lbl_dir = os.path.join(BASE_DIR, f'_tmp_fold_{fold_idx}', split, 'labels')
    os.makedirs(fold_img_dir, exist_ok=True)
    os.makedirs(fold_lbl_dir, exist_ok=True)

    split_file = os.path.join(SPLITS_DIR, f'fold_{fold_idx}',
                              'train.txt' if split == 'train' else 'test.txt')

    with open(split_file, 'r') as f:
        image_paths = [
            line.strip() if os.path.isabs(line.strip())
            else os.path.join(BASE_DIR, line.strip())
            for line in f if line.strip()
        ]

    for img_path in image_paths:
        filename = os.path.basename(img_path)
        stem     = os.path.splitext(filename)[0]

        # Copie (ou lien) image
        dst_img = os.path.join(fold_img_dir, filename)
        if not os.path.exists(dst_img):
            shutil.copy2(img_path, dst_img)

        # Copie annotation correspondante
        lbl_src = os.path.join(LABELS_DIR, stem + '.txt')
        dst_lbl = os.path.join(fold_lbl_dir, stem + '.txt')
        if os.path.exists(lbl_src) and not os.path.exists(dst_lbl):
            shutil.copy2(lbl_src, dst_lbl)

    return os.path.join(BASE_DIR, f'_tmp_fold_{fold_idx}', split)


def create_fold_yaml(fold_idx, base_config):
    """
    Génère un fichier data_fold_X.yaml temporaire pour ce fold,
    avec les bons chemins train/val.
    """
    train_dir = build_fold_image_dirs(fold_idx, 'train')
    val_dir   = build_fold_image_dirs(fold_idx, 'val')

    fold_config = {
        'train': train_dir,
        'val':   val_dir,
        'nc':    base_config['nc'],
        'names': base_config['names'],
    }

    yaml_path = os.path.join(BASE_DIR, f'data_fold_{fold_idx}.yaml')
    with open(yaml_path, 'w', encoding='utf-8') as f:
        yaml.dump(fold_config, f, allow_unicode=True)

    return yaml_path


def cleanup_fold(fold_idx, yaml_path):
    """Supprime les dossiers temporaires et le yaml du fold."""
    tmp_dir = os.path.join(BASE_DIR, f'_tmp_fold_{fold_idx}')
    if os.path.exists(tmp_dir):
        shutil.rmtree(tmp_dir)
    if os.path.exists(yaml_path):
        os.remove(yaml_path)


def train_fold(fold_idx, base_config):
    print(f"\n{'='*60}")
    print(f"  FOLD {fold_idx + 1} / {N_SPLITS}")
    print(f"{'='*60}\n")

    yaml_path = create_fold_yaml(fold_idx, base_config)

    model = YOLO(MODEL_WEIGHTS)

    model.train(
        data    = yaml_path,
        epochs  = EPOCHS,
        imgsz   = IMG_SIZE,
        batch   = BATCH_SIZE,
        device  = DEVICE,
        project = OUTPUT_DIR,
        name    = f'fold_{fold_idx}',
        exist_ok= True,
        verbose = True,
    )

    # Sauvegarde des métriques du fold
    results_src = os.path.join(OUTPUT_DIR, f'fold_{fold_idx}', 'results.csv')
    if os.path.exists(results_src):
        print(f"  → Résultats sauvegardés dans {results_src}")

    cleanup_fold(fold_idx, yaml_path)
    print(f"\n  Fold {fold_idx} terminé.\n")


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    base_config = load_base_config(DATA_CONFIG)

    print(f"Début de l'entraînement K-Fold ({N_SPLITS} folds)")
    print(f"Modèle : {MODEL_WEIGHTS}  |  Epochs : {EPOCHS}  |  Device : CUDA:{DEVICE}\n")

    for fold_idx in range(N_SPLITS):
        train_fold(fold_idx, base_config)

    print("\n✓ Entraînement K-Fold terminé !")
    print(f"  Les poids de chaque fold sont dans : {OUTPUT_DIR}/fold_X/weights/best.pt")


if __name__ == "__main__":
    main()